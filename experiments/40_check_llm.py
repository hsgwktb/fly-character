import subprocess, os
def sh(c): return subprocess.run(c, shell=True, executable="/bin/bash", capture_output=True, text=True).stdout.strip()
print("=== llama.cpp 编译产物 ===")
print(sh("ls -la /content/llama.cpp/build/bin/llama-server 2>/dev/null || echo '(不存在)'"))
print("=== 模型文件 ===")
print(sh("ls -la /content/model* 2>/dev/null | head -5 || echo '(无)'"))
print(sh("find /content -maxdepth 3 -name '*.gguf' -printf '%s %p\n' 2>/dev/null | head -5 || true"))
print("=== 是否有 llama-server 在跑 ===")
print(sh("ps -eo pid,etime,cmd | grep [l]lama-server | head -3 || echo '(未运行)'"))
print("=== 端口占用 ===")
print(sh("ss -ltnp 2>/dev/null | grep -E ':(8000|8080|8081|8082)' || echo '(以上都没占用)'"))
print("=== 显存 ===")
print(sh("nvidia-smi --query-gpu=memory.used,memory.total --format=csv,noheader"))
print("=== 我自己的角色服务 ===")
print(sh("ps -eo pid,cmd | grep [w]ebui_character.py | head -2 || echo '(未运行)'"))
